import { z } from 'zod';


export const createEmployeeSchema = z.object({
  companyId: z.string().min(1, 'Company is required'),
  branchId: z.string().min(1, 'Branch is required'),
  departmentId: z.string().min(1, 'Department is required'),
  attendancePolicyId: z.string().min(1, 'Attendance Policy is required'),
  employeeNumber: z.string().min(1, 'Employee Number is required').max(50, 'Max 50 characters'),
  firstName: z.string().min(1, 'First Name is required').max(100, 'Max 100 characters'),
  lastName: z.string().min(1, 'Last Name is required').max(100, 'Max 100 characters'),
  middleName: z.string().max(100).optional().nullable(),
  preferredName: z.string().max(100).optional().nullable(),
  nationalId: z.string().max(50).optional().nullable(),
  passportNumber: z.string().max(50).optional().nullable(),
  email: z.string().min(1, 'Email is required').email('Invalid email format').max(256),
  phoneNumber: z.string().min(1, 'Phone Number is required').max(20),
  dateOfBirth: z.string().min(1, 'Date of Birth is required'),
  gender: z.union([z.literal(0), z.literal(1), z.literal(2)]),
  hireDate: z.string().min(1, 'Hire Date is required'),
  jobTitle: z.string().min(1, 'Job Title is required').max(200),
  street: z.string().min(1, 'Street is required').max(500),
  city: z.string().min(1, 'City is required').max(200),
  state: z.string().min(1, 'State is required').max(200),
  zipCode: z.string().min(1, 'Zip Code is required').max(20),
  country: z.string().min(1, 'Country is required').max(200),
});

